"""
Pydantic schemas for chat endpoints, request validation, and responses.
"""
from typing import List, Optional, Any, Dict, Literal
from pydantic import BaseModel, Field, field_validator


class HealthResponse(BaseModel):
    """Response model for GET /health."""
    status: str = Field(default="ok", description="Application status")
    keys_configured: int = Field(description="Number of configured LLM API keys")
    cache_enabled: bool = Field(description="Whether response caching is enabled")


class ChatRequest(BaseModel):
    """Request model for POST /chat."""
    session_id: str = Field(
        ...,
        min_length=1,
        max_length=128,
        description="Unique session identifier generated by the client"
    )
    message: str = Field(
        ...,
        description="User message text, between 1 and 4000 characters after trimming whitespace"
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional system prompt overriding the default for this session"
    )

    @field_validator("message")
    @classmethod
    def validate_message(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Message cannot be empty or solely whitespace")
        if len(trimmed) > 4000:
            raise ValueError("Message cannot exceed 4000 characters after trimming")
        return trimmed

    @field_validator("session_id")
    @classmethod
    def validate_session_id(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("session_id cannot be empty or solely whitespace")
        if len(trimmed) > 128:
            raise ValueError("session_id cannot exceed 128 characters")
        return trimmed


class ChatResponseMetadata(BaseModel):
    """Metadata schema for an assistant response."""
    resolution_source: Literal["LIVE_INFERENCE", "LLM_CACHE"] = Field(
        description="Whether response came from live inference or LiteLLM cache"
    )
    model: str = Field(description="Model identifier that produced the response")
    latency_ms: int = Field(description="Server-measured time for this request in milliseconds")
    input_tokens: int = Field(description="Prompt tokens for this request (system + history + new message)")
    output_tokens: int = Field(description="Completion tokens for this response")
    key_id: Optional[str] = Field(
        default=None,
        description="Identifier of the key that answered (key_1, key_2, ...). null on LLM_CACHE."
    )
    fallback_attempts: int = Field(
        default=0,
        description="Count of failed keys before success. 0 on LLM_CACHE."
    )


class ChatResponse(BaseModel):
    """Response model for POST /chat."""
    session_id: str = Field(description="Echo of the session_id")
    reply: str = Field(description="Assistant response text, non-empty")
    metadata: ChatResponseMetadata = Field(description="Per-request execution metadata")


class MessageItem(BaseModel):
    """Item representing a single message in session history."""
    role: Literal["user", "assistant"] = Field(description="'user' or 'assistant'")
    content: str = Field(description="Message text content")
    metadata: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Optional metadata for assistant messages"
    )


class SessionHistoryResponse(BaseModel):
    """Response model for GET /sessions/{session_id}/messages."""
    session_id: str = Field(description="Session identifier")
    messages: List[MessageItem] = Field(description="List of messages in chronological order")
